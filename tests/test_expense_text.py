from datetime import date

import pytest

from flat_expense.expense_text import extract

TODAY = date(2026, 11, 7)


@pytest.mark.parametrize(
    "text,amount,paid_on",
    [
        ("Вчера заплатил мастеру 3 731,15 рублей", "3731.15", "2026-11-06"),
        ("Купил 10 мешков штукатурки за 4500 рублей", "4500.00", "2026-11-07"),
        ("Оплатил диван 50 тысяч рублей", "50000.00", "2026-11-07"),
        ("05.11.2026 оплатил холодильник 85000 руб", "85000.00", "2026-11-05"),
        ("Аванс за работы 20000 рублей, полная стоимость работ 80000", "20000.00", "2026-11-07"),
        ("Штукатурка 1200", "1200.00", "2026-11-07"),
        ("Штукатурка 100.50", "100.50", "2026-11-07"),
        ("Оплатил дизайнеру", None, "2026-11-07"),
        ("Оплатил мастеру 1.005 рублей", None, "2026-11-07"),
        ("Оплатил мастеру -100 рублей", None, "2026-11-07"),
        ("Оплатил мастеру 0 рублей", None, "2026-11-07"),
        ("Оплатил мастеру 10000000000 рублей", None, "2026-11-07"),
        ("В октябре оплатил мастеру 100 рублей", "100.00", None),
        ("31.02.2026 оплатил мастеру 100 рублей", "100.00", None),
        ("Позавчера оплатил 12к за двери", "12000.00", "2026-11-05"),
        ("Оплатил 1\u202f234,50 за материалы", "1234.50", "2026-11-07"),
    ],
)
def test_extract_does_not_invent_or_round_money(text, amount, paid_on):
    result = extract(text, TODAY)
    assert result["is_expense"] is True
    assert result["values"].get("amount") == amount
    assert result["values"].get("paid_on") == paid_on
    assert result["values"]["description"] == text


@pytest.mark.parametrize(
    "text",
    [
        "Планирую купить диван за 50000 рублей",
        "Куплю диван 50000",
        "Оплатил мастеру 2000 рублей и купил цемент за 3000 рублей",
        "Оплатил мастеру 2000 и купил цемент за 3000 рублей",
        "Привет",
        "Расскажи о погоде",
        "Возврат 2000",
        "Оплатил 100 долларов",
    ],
)
def test_ambiguous_or_nonpayment_text_is_not_an_expense(text):
    assert extract(text, TODAY)["is_expense"] is False
